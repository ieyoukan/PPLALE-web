import { test, expect } from '@playwright/test';

const base = process.env.PPLALE_ROOM_TEST_URL;
test.skip(!base, 'set PPLALE_ROOM_TEST_URL to a web app connected to a room server');

test('the seat opens deck thumbnails, previews a candidate and confirms it without losing the room', async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${base}/game/`);
  await page.waitForURL(/\/game\/room\/\d{6}\/$/, { timeout: 30000 });
  const roomURL = page.url();
  await page.getByRole('button', { name: 'この席にすわる' }).first().click();
  await page.getByRole('button', { name: /^デッキ:/ }).click();
  const list = page.getByRole('dialog', { name: 'デッキをえらぶ' });
  const trial = list.getByRole('button', { name: /いちごのおためしデッキ/ });
  await expect(trial).toHaveAttribute('aria-pressed', 'true');
  await expect(list.getByRole('img', { name: 'いちごのおためしデッキのデッキ画像' })).toBeVisible();
  await trial.click();
  const preview = page.getByRole('dialog', { name: 'いちごのおためしデッキ' });
  const layout = preview.getByRole('group', { name: 'デッキのカード' });
  await expect(layout.locator('[data-kind="yojo"]')).toHaveCount(20);
  await expect(layout.locator('[data-kind="sweet"]')).toHaveCount(10);
  await expect(layout.locator('[data-kind="playable"]')).toHaveCount(1);
  await expect(preview.getByRole('button', { name: 'このデッキにする', exact: true })).toBeInViewport();
  const contents = preview.locator(':scope > div').last();
  const card = layout.locator('[data-kind="sweet"]').first();
  await card.scrollIntoViewIfNeeded();
  const firstYojo = await layout.locator('[data-kind=yojo]').first().boundingBox();
  const firstSweet = await layout.locator('[data-kind=sweet]').first().boundingBox();
  const playable = await layout.locator('[data-kind=playable]').boundingBox();
  expect(firstYojo.x + firstYojo.width).toBeLessThan(firstSweet.x);
  expect(playable.y).toBeGreaterThan(firstSweet.y + firstSweet.height);
  expect(Math.abs(playable.x - firstSweet.x)).toBeLessThan(1);
  const scrollBefore = await contents.evaluate(element => element.scrollTop);
  await card.click();
  const enlarged = page.getByRole('dialog', { name: /の拡大表示$/ });
  await expect(enlarged).toBeVisible();
  expect((await enlarged.getByRole('img').first().boundingBox()).height).toBeGreaterThan(400);
  const enlargedFace = enlarged.getByRole('img').first();
  const initialRotation = await enlargedFace.evaluate(image => getComputedStyle(image.parentElement.parentElement).transform);
  await page.mouse.move(1000, 160);
  await expect.poll(() => enlargedFace.evaluate(image => getComputedStyle(image.parentElement.parentElement).transform)).not.toBe(initialRotation);

  await expect(preview.locator('../..')).toHaveAttribute('inert', '');
  await page.keyboard.press('Escape');
  await expect(enlarged).toHaveCount(0);
  await expect(preview).toBeVisible();
  await expect(card).toBeFocused();
  expect(await contents.evaluate(element => element.scrollTop)).toBe(scrollBefore);
  await card.click();
  await enlarged.getByRole('button', { name: '拡大表示を閉じる', exact: true }).click();
  await expect(enlarged).toHaveCount(0);
  await expect(preview).toBeVisible();
  await preview.getByRole('button', { name: '閉じる', exact: true }).click();
  await expect(list).toBeVisible();
  await list.getByRole('button', { name: /おまかせデッキ/ }).click();
  const random = page.getByRole('dialog', { name: 'おまかせデッキ', exact: true });
  await expect(random).toContainText('対戦の準備ができたときにカードが決まります');
  await random.getByRole('button', { name: 'このデッキにする', exact: true }).click();
  await expect(page.getByRole('button', { name: 'デッキ: おまかせデッキ', exact: true })).toBeVisible();
  await expect(page).toHaveURL(roomURL);
  await page.getByRole('button', { name: /^デッキ:/ }).click();
  await expect(list.getByRole('button', { name: /おまかせデッキ/ })).toHaveAttribute('aria-pressed', 'true');
  await list.getByRole('button', { name: '閉じる', exact: true }).click();
  await page.getByRole('button', { name: 'じゅんびOK!', exact: true }).click();
  await page.getByRole('button', { name: /^デッキ:/ }).click();
  await expect(random).toBeVisible();
  await expect(random.getByRole('button', { name: 'このデッキにする' })).toHaveCount(0);
  expect(errors).toEqual([]);
});

test('the gallery shares the rotating card viewer, including tokens', async ({ page }) => {
  await page.goto(`${base}/game/cards/zukan/`);
  await page.getByRole('tab', { name: /トークン/ }).click();
  const token = page.getByRole('tabpanel').getByRole('list').getByRole('button').first();
  await token.click();
  const enlarged = page.getByRole('dialog', { name: /の拡大表示$/ });
  await expect(enlarged).toBeVisible();
  const face = enlarged.getByRole('img').first();
  const initial = await face.evaluate(image => getComputedStyle(image.parentElement.parentElement).transform);
  await page.mouse.move(1000, 150);
  await expect.poll(() => face.evaluate(image => getComputedStyle(image.parentElement.parentElement).transform)).not.toBe(initial);
  await page.keyboard.press('Escape');
  await expect(enlarged).toHaveCount(0);
  await expect(token).toBeFocused();
});
